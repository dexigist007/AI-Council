/**
 * Writes docs/app-store/privacy-policy.html from the in-app privacy text, so the hosted policy and
 * the app never disagree.  Usage: npx vite-node scripts/privacy-html.ts
 */
import { writeFileSync } from 'node:fs'
import { SUPPORT_EMAIL } from '@/config/app'
import { messages } from '@/i18n/locales'

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const email = SUPPORT_EMAIL || 'SUPPORT_EMAIL'

function section(lang: 'en' | 'tr'): string {
  const p = messages[lang].shell.privacyPage as Record<string, string>
  const parts = [`<h1>${esc(p.title!)}</h1>`, `<p class="meta">${esc(p.updated!)}</p>`]
  for (let n = 1; n <= 7; n++) {
    const body = esc(p[`s${n}`]!).replace('{email}', `<a href="mailto:${email}">${email}</a>`)
    parts.push(`<h2>${esc(p[`s${n}h`]!)}</h2>\n<p>${body}</p>`)
  }
  return parts.join('\n')
}

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Conclave — Privacy policy</title>
<!-- Generated by scripts/privacy-html.ts. Host it (e.g. GitHub Pages) and use its URL in App Store Connect. -->
<style>
body { font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; max-width: 68ch; margin: 48px auto; padding: 0 20px; color: #1a1d23; background: #f7f8fa; }
h1 { font-size: 28px; margin: 0; } h2 { font-size: 18px; margin: 28px 0 6px; } .meta { color: #5f6673; margin-top: 4px; }
hr { margin: 56px 0; border: 0; border-top: 1px solid #e2e5ea; } a { color: #1e7a6e; }
@media (prefers-color-scheme: dark) { body { background: #191b20; color: #e7e9ed; } .meta { color: #9aa1ad; } hr { border-color: #2d3139; } a { color: #4dbcab; } }
</style>
</head>
<body>
${section('en')}
<hr>
<div lang="tr">
${section('tr')}
</div>
</body>
</html>
`
writeFileSync(new URL('../docs/app-store/privacy-policy.html', import.meta.url), html)
console.log(SUPPORT_EMAIL ? 'written' : 'written with a SUPPORT_EMAIL placeholder — set it in src/config/app.ts and run again')
